"""Where uploaded KYC documents are kept: a local directory (a mounted volume in production).

Files are named by a random id, never by anything the client sent, and their type is taken from their
first bytes, so a script renamed to .pdf is refused. They are only ever served to the shop's owner and
admins, through the API.
"""

import os
import uuid
from pathlib import Path
from typing import Optional

from app.config import settings

# Content type -> (file extension, the bytes such a file starts with).
ALLOWED_TYPES = {
    "application/pdf": ("pdf", (b"%PDF-",)),
    "image/jpeg": ("jpg", (b"\xff\xd8\xff",)),
    "image/png": ("png", (b"\x89PNG\r\n\x1a\n",)),
    "image/webp": ("webp", (b"RIFF",)),
}


class StorageDisabled(Exception):
    pass


def sniff_content_type(data: bytes, declared: Optional[str]) -> Optional[str]:
    """The declared type when the file really is one; None for anything else."""
    declared = (declared or "").split(";")[0].strip().lower()
    if declared not in ALLOWED_TYPES:
        return None
    _, magics = ALLOWED_TYPES[declared]
    if not any(data.startswith(m) for m in magics):
        return None
    if declared == "image/webp" and data[8:12] != b"WEBP":
        return None
    return declared


class LocalDocumentStorage:
    def __init__(self, root: str):
        self.root = Path(root) if root else None

    @property
    def enabled(self) -> bool:
        return self.root is not None

    def _path(self, key: str) -> Path:
        if self.root is None:
            raise StorageDisabled()
        # Keys are generated by save(): "<shop id>/<uuid>.<ext>". Anything else is refused.
        path = (self.root / key).resolve()
        if self.root.resolve() not in path.parents:
            raise ValueError("Invalid storage key")
        return path

    def save(self, shop_id: str, data: bytes, content_type: str) -> str:
        if self.root is None:
            raise StorageDisabled()
        ext = ALLOWED_TYPES[content_type][0]
        # A folder per shop, named so that no shop id can reach outside the root.
        folder = str(uuid.UUID(shop_id)) if _is_uuid(shop_id) else uuid.uuid5(uuid.NAMESPACE_URL, shop_id).hex
        key = f"{folder}/{uuid.uuid4()}.{ext}"
        path = self._path(key)
        path.parent.mkdir(parents=True, exist_ok=True)
        tmp = path.with_suffix(".part")
        with open(tmp, "wb") as f:
            f.write(data)
        os.replace(tmp, path)
        return key

    def path_of(self, key: str) -> Path:
        return self._path(key)

    def delete(self, key: str) -> None:
        try:
            self._path(key).unlink(missing_ok=True)
        except (StorageDisabled, ValueError, OSError):
            pass


def _is_uuid(value: str) -> bool:
    try:
        uuid.UUID(value)
        return True
    except ValueError:
        return False


def get_storage() -> LocalDocumentStorage:
    return LocalDocumentStorage(settings.DOCUMENT_STORAGE_DIR)
